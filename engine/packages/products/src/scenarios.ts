import { readFile, writeFile, mkdir } from "node:fs/promises";
import { join } from "node:path";
import { parse as parseYaml, stringify as stringifyYaml } from "yaml";
import { WorkflowSchema, formatZodError, type Workflow } from "@demoforge/contracts";
import { DemoForgeError, fileExists } from "@demoforge/shared";
import type { LoadedProduct } from "./loader";

export function scenarioPath(product: Pick<LoadedProduct, "dir">, id: string): string {
  return join(product.dir, "scenarios", `${id}.yaml`);
}

export async function loadScenario(product: Pick<LoadedProduct, "dir" | "id">, id: string): Promise<Workflow> {
  let file = scenarioPath(product, id);
  if (!(await fileExists(file))) file = file.replace(/\.yaml$/, ".yml");
  if (!(await fileExists(file))) {
    throw new DemoForgeError("SCENARIO_NOT_FOUND", `Scenario '${id}' was not found for product '${product.id}'.`, {
      hint: `Expected ${scenarioPath(product, id)}. Run \`demoforge products inspect ${product.id}\` to list scenarios.`,
    });
  }
  return parseWorkflow(await readFile(file, "utf8"), file);
}

export function parseWorkflow(text: string, source = "workflow"): Workflow {
  let raw: unknown;
  try {
    raw = parseYaml(text);
  } catch (error) {
    throw new DemoForgeError("CONFIG_INVALID", `Could not parse ${source}: ${(error as Error).message}`);
  }
  const parsed = WorkflowSchema.safeParse(raw);
  if (!parsed.success) {
    throw new DemoForgeError("CONFIG_INVALID", `Invalid workflow in ${source}:\n${formatZodError(parsed.error)}`);
  }
  return parsed.data;
}

export function workflowToYaml(workflow: Workflow): string {
  const header =
    workflow.created_by === "ai" && !workflow.approved
      ? "# Generated by DemoForge. Review every step, then set `approved: true` to use it for automated videos.\n"
      : "";
  return header + stringifyYaml(workflow, { lineWidth: 110 });
}

/** Save a scenario. Never overwrites an existing file unless `overwrite` is set. */
export async function saveScenario(
  product: Pick<LoadedProduct, "dir">,
  workflow: Workflow,
  options: { overwrite?: boolean } = {},
): Promise<string> {
  const file = scenarioPath(product, workflow.id);
  if (!options.overwrite && (await fileExists(file))) {
    throw new DemoForgeError("CONFIG_INVALID", `Scenario file ${file} already exists.`);
  }
  await mkdir(join(product.dir, "scenarios"), { recursive: true });
  await writeFile(file, workflowToYaml(workflow), "utf8");
  return file;
}
